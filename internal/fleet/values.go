package fleet

import (
	"encoding/json"
	"fmt"
	"sort"
	"strconv"
	"strings"
)

// HubInfo is what a member's generated values say about its hub.
type HubInfo struct {
	// URL: the hub's console address, as members and browsers reach it.
	URL string
	// PublicKeys: the hub's public key(s), PEM.
	PublicKeys string
	// CACert: the CA of the hub's address when it is not a public one
	// (PEM); "" otherwise.
	CACert string
}

// Install is what "Add a cluster" hands over: the box's values and the
// commands that install it.
type Install struct {
	// File: the values file's name; Values: its text.
	File, Values string
	// Commands: shell commands, in order. JoinToken, when one was issued,
	// is in them (shown once).
	Commands []string
	Upgrade  bool
}

// ChartRef is where the box's chart is published (the release workflow
// pushes the charts there; the install docs use the same address).
const ChartRef = "oci://ghcr.io/hoobiboobi/charts/ci-accelerator"

// Generate makes a cluster's values and commands from its settings.
// joinToken: the secret of a join token issued now ("" when the cluster
// joins with a public key, or for an upgrade).
func Generate(s Settings, hub HubInfo, version, joinToken string, upgrade bool) Install {
	v := map[string]any{}
	set := func(path string, val any) {
		m := v
		parts := strings.Split(path, ".")
		for _, p := range parts[:len(parts)-1] {
			next, ok := m[p].(map[string]any)
			if !ok {
				next = map[string]any{}
				m[p] = next
			}
			m = next
		}
		m[parts[len(parts)-1]] = val
	}
	vals := s.Values
	kept := s.Kept()
	for _, p := range Params {
		if p.Path == "" || !p.Applies(vals) {
			continue
		}
		val := vals[p.Key]
		if val == "" {
			val = p.Default
		}
		if val == "" {
			continue
		}
		if p.Kind == KindNumber {
			n, _ := strconv.Atoi(val)
			set(p.Path, n)
		} else {
			set(p.Path, val)
		}
	}
	set("global.console.url", hub.URL)
	set("control-plane.fleet.role", "member")
	set("control-plane.fleet.name", s.Member)
	set("control-plane.fleet.hub.url", hub.URL)
	set("control-plane.fleet.hub.publicKeys", hub.PublicKeys)
	if hub.CACert != "" {
		set("control-plane.fleet.hub.caCert", hub.CACert)
	}
	// A member registered by its key joins with that key, whatever the
	// settings say (the API registers by key and keeps no "joins").
	byKey := vals["joins"] == "key" || s.RegisteredByKey
	if byKey {
		set("control-plane.fleet.key.existingSecret", "fleet-key")
	} else {
		set("control-plane.fleet.join.existingSecret", "fleet-join")
	}
	// Secrets the hub delivers over the link: written in the release's
	// namespace once the box is connected.
	set("gitlab-runner.runners.secret", SecretRunner)
	if kept["gitlab_token"] {
		set("control-plane.gitlab.token.existingSecret", SecretGitLab)
	}
	if vals["s3_server"] != "" {
		set("gitlab-runner.runners.cache.secretName", SecretS3)
	}
	var b strings.Builder
	fmt.Fprintf(&b, "# %s: a member of the fleet at %s.\n", s.Member, oneLine(hub.URL))
	fmt.Fprintf(&b, "# Generated by the hub from the cluster's settings (list v%d); change them\n", s.Version)
	b.WriteString("# at the hub and take the new file, rather than editing this one.\n")
	b.WriteString("# The runner's token and the S3 keys are not here: the hub sends them\n")
	b.WriteString("# over the cluster's link once it is connected (Secrets " + SecretRunner + ", ...).\n")
	writeYAML(&b, v, 0)

	in := Install{File: s.Member + ".values.yaml", Values: b.String(), Upgrade: upgrade}
	const ns = "ci-accelerator"
	// apply: the commands can run again (a new join token replaces the
	// Secret of an earlier one).
	const apply = " --dry-run=client -o yaml | kubectl apply -f -"
	if !upgrade {
		in.Commands = append(in.Commands, "# The box's prerequisites first (cert-manager, the build nodes' label and\n"+
			"# taint): docs/install.md, steps 1 to 3.\n"+
			"kubectl create namespace "+ns+apply)
		switch {
		case joinToken != "":
			in.Commands = append(in.Commands, "# The join token: works once, for "+s.Member+" only; replaces an earlier one.\n"+
				"kubectl -n "+ns+" create secret generic fleet-join --from-literal=token="+joinToken+apply)
		case byKey:
			in.Commands = append(in.Commands, "# The private key of the public key registered for "+s.Member+".\n"+
				"kubectl -n "+ns+" create secret generic fleet-key --from-file=key=./"+s.Member+".key"+apply)
		}
	}
	in.Commands = append(in.Commands, fmt.Sprintf("helm upgrade --install ci-accelerator %s --version %s \\\n  -n %s -f %s", ChartRef, version, ns, in.File))
	return in
}

// writeYAML writes a map as YAML: keys sorted, strings JSON-quoted (valid
// YAML), PEM blocks as literal blocks.
func writeYAML(b *strings.Builder, m map[string]any, indent int) {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	pad := strings.Repeat("  ", indent)
	for _, k := range keys {
		switch val := m[k].(type) {
		case map[string]any:
			fmt.Fprintf(b, "%s%s:\n", pad, k)
			writeYAML(b, val, indent+1)
		case string:
			if block(val) {
				fmt.Fprintf(b, "%s%s: |\n", pad, k)
				for _, line := range strings.Split(strings.TrimRight(val, "\n"), "\n") {
					fmt.Fprintf(b, "%s  %s\n", pad, line)
				}
				continue
			}
			fmt.Fprintf(b, "%s%s: %s\n", pad, k, quote(val))
		default:
			fmt.Fprintf(b, "%s%s: %v\n", pad, k, val)
		}
	}
}

// block says whether a string is written as a literal block: several
// lines of printable ASCII, the first one not empty or indented (a YAML
// reader takes the block's indentation from it).
func block(v string) bool {
	if !strings.Contains(v, "\n") || strings.IndexAny(v[:1], " \t\n") == 0 {
		return false
	}
	for i := 0; i < len(v); i++ {
		if c := v[i]; c != '\n' && (c < 0x20 || c > 0x7e) {
			return false
		}
	}
	return true
}

// quote writes a string as a double-quoted YAML scalar: JSON, with what
// YAML reads differently from JSON (DEL, C1 controls with U+0085 among
// them, U+FFFE and U+FFFF) escaped.
func quote(v string) string {
	q, _ := json.Marshal(v)
	var b strings.Builder
	for _, r := range string(q) {
		if (r >= 0x7f && r <= 0x9f) || r == 0xfffe || r == 0xffff {
			fmt.Fprintf(&b, "\\u%04x", r)
			continue
		}
		b.WriteRune(r)
	}
	return b.String()
}

// oneLine drops from v what a YAML reader takes as a line break or does
// not read (for a comment).
func oneLine(v string) string {
	return strings.Map(func(r rune) rune {
		if r < 0x20 || (r >= 0x7f && r <= 0x9f) || r == 0x2028 || r == 0x2029 || r == 0xfffe || r == 0xffff {
			return -1
		}
		return r
	}, v)
}
